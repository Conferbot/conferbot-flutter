#!/bin/sh
# Rebuilds lib/src/core/customization/fonts_data.dart (the owner font
# catalog and the widget themes' Google Fonts queries) from the React Native
# SDK's src/core/fonts.data.ts, itself copied from conferbot-widget
# src/ts/fonts/catalog.ts and src/ts/theme/registry.ts. Run it after
# fonts.data.ts changes in RN, then commit the file. Set RN_SDK if the repo
# is not next door. test/core/customization/owner_font_test.dart fails when
# the copy drifts from RN's or the widget's.
#
#   sh tool/sync_fonts.sh          writes the Dart file
#   sh tool/sync_fonts.sh --check  exits 1 when it is out of date
set -e
here="$(cd "$(dirname "$0")/.." && pwd)"
rn="${RN_SDK:-$here/../conferbot-react-native}"
out="$here/lib/src/core/customization/fonts_data.dart"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
(cd "$rn" && npx tsc src/core/fonts.data.ts --outDir "$tmp/js" --module commonjs --target es2019 --skipLibCheck >/dev/null)
node - "$tmp/js/fonts.data.js" "$out" "$1" <<'JS'
const fs = require('fs');
const [src, out, flag] = process.argv.slice(2);
const F = require(src);
const q = (s) => (s === null ? 'null' : JSON.stringify(s).replace(/\$/g, '\\$'));
const lines = [
  '/// The owner font catalog and the widget themes\' Google Fonts queries.',
  '/// Generated by tool/sync_fonts.sh from the React Native SDK\'s',
  '/// src/core/fonts.data.ts (conferbot-widget src/ts/fonts/catalog.ts, the',
  '/// list the dashboard picker uses, and src/ts/theme/registry.ts). Do not',
  '/// edit; change the source and run the script.',
  'library;',
  '',
  'class CatalogFont {',
  '  final String id;',
  '  final String label;',
  '  final String family;',
  '  final String category;',
  '  final String stack;',
  '',
  '  /// The Google Fonts css2 "family=" query, or null for a system font.',
  '  final String? google;',
  '  const CatalogFont(this.id, this.label, this.family, this.category, this.stack, this.google);',
  '}',
  '',
  'const List<CatalogFont> fontCatalog = [',
  ...F.FONT_CATALOG.map((f) => `  CatalogFont(${q(f.id)}, ${q(f.label)}, ${q(f.family)}, ${q(f.category)}, ${q(f.stack)}, ${q(f.google)}),`),
  '];',
  '',
  '/// Theme font family -> its Google Fonts css2 "family=" query.',
  'const Map<String, String> themeFontQueries = {',
  ...Object.entries(F.THEME_FONT_QUERIES).map(([k, v]) => `  ${q(k)}: ${q(v)},`),
  '};',
  '',
];
const text = lines.join('\n');
if (flag === '--check') {
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (now !== text) { console.error('fonts_data.dart is out of date: run sh tool/sync_fonts.sh'); process.exit(1); }
  console.log('fonts_data.dart is up to date');
} else {
  fs.writeFileSync(out, text);
  console.log(`${F.FONT_CATALOG.length} fonts, ${Object.keys(F.THEME_FONT_QUERIES).length} theme fonts written`);
}
JS

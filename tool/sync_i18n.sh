#!/bin/sh
# Rebuild the widget languages (lib/src/core/i18n/strings_<lang>.dart,
# i18n_strings.dart and i18n_games.dart) from the React Native SDK's
# scripts/parity/i18n/strings.json, the table all SDKs share (the web's 824
# keys from conferbot-widget ts/i18n/*.ts, plus the sdk.* words only the SDKs
# draw, in en/nl/fr/de/es, and the waiting games' quiz and word scramble per
# language). Run `node gen.js` in RN first when the widget or
# sdk-strings.json changed, then this, then commit the files.
#
#   sh tool/sync_i18n.sh          writes the Dart files
#   sh tool/sync_i18n.sh --check  exits 1 when they are out of date
#
# CONFERBOT_DEV is the folder holding sdk/ (default: two levels up).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
DEV="${CONFERBOT_DEV:-$(cd "$HERE/../../.." && pwd)}"
JSON="$DEV/sdk/conferbot-react-native/scripts/parity/i18n/strings.json"
OUT="$HERE/../lib/src/core/i18n"
[ -f "$JSON" ] || { echo "not found: $JSON" >&2; exit 1; }
mkdir -p "$OUT"
node - "$JSON" "$OUT" "$1" <<'JS'
const fs = require('fs');
const path = require('path');
const [json, out, flag] = process.argv.slice(2);
const d = JSON.parse(fs.readFileSync(json, 'utf8'));
const LANGS = d.languages;
const keys = Object.keys(d.strings.en);
const sdk = new Set(d.sdkKeys);
// A Dart string literal: JSON escapes, with $ escaped for interpolation.
const q = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
const cap = (l) => l[0].toUpperCase() + l.slice(1);
const head = (what) => [
  `/// ${what}`,
  "/// Generated by tool/sync_i18n.sh from the React Native SDK's",
  '/// scripts/parity/i18n/strings.json (conferbot-widget ts/i18n/<lang>.ts and',
  '/// sdk-strings.json). Do not edit; change the source and run the script.',
  'library;',
  '',
];
const files = {};
for (const l of LANGS) {
  const s = head(`${d.names[l]}: the widget's own words by key.`);
  s.push('// A top-level final: built the first time the language is drawn.');
  s.push(`final Map<String, String> i18n${cap(l)} = <String, String>{`);
  for (const k of keys) if (typeof d.strings[l][k] === 'string') s.push(`  ${q(k)}: ${q(d.strings[l][k])},`);
  s.push('};');
  files[`strings_${l}.dart`] = s.join('\n') + '\n';
}
const x = head('Every key and each language\'s table.');
for (const l of LANGS) x.push(`import 'strings_${l}.dart';`);
x.push('');
x.push(`/// Every key, the web's first (${keys.length - sdk.size}), then the SDK's own (sdk.*, ${sdk.size}).`);
x.push('const List<String> i18nKeys = <String>[');
for (const k of keys) x.push(`  ${q(k)},`);
x.push('];');
x.push('');
x.push(`/// How many of [i18nKeys] are the SDK's own (sdk.*).`);
x.push(`const int i18nSdkKeyCount = ${sdk.size};`);
x.push('');
x.push('/// The supported languages, English first.');
x.push(`const List<String> i18nLanguages = <String>[${LANGS.map(q).join(', ')}];`);
x.push('');
x.push('/// Each language\'s own name, for pickers.');
x.push('const Map<String, String> i18nLanguageNames = <String, String>{');
for (const l of LANGS) x.push(`  ${q(l)}: ${q(d.names[l])},`);
x.push('};');
x.push('');
x.push('/// One language\'s table (English for anything else).');
x.push('Map<String, String> i18nTableOf(String lang) {');
x.push('  switch (lang) {');
for (const l of LANGS.slice(1)) { x.push(`    case ${q(l)}:`); x.push(`      return i18n${cap(l)};`); }
x.push('    default:');
x.push(`      return i18n${cap(LANGS[0])};`);
x.push('  }');
x.push('}');
files['i18n_strings.dart'] = x.join('\n') + '\n';
const g = head('The waiting games\' quiz and word scramble per language (web ts/chat/games/content.ts).');
g.push("import '../waiting/games_logic.dart' show Trivia, Word;");
g.push('');
g.push('/// The quiz in [lang] (English for anything else).');
g.push('List<Trivia> i18nTriviaOf(String lang) {');
g.push('  switch (lang) {');
for (const l of LANGS.slice(1)) { g.push(`    case ${q(l)}:`); g.push(`      return _trivia${cap(l)};`); }
g.push('    default:');
g.push(`      return _trivia${cap(LANGS[0])};`);
g.push('  }');
g.push('}');
g.push('');
g.push('/// The word scramble in [lang] (English for anything else).');
g.push('List<Word> i18nWordsOf(String lang) {');
g.push('  switch (lang) {');
for (const l of LANGS.slice(1)) { g.push(`    case ${q(l)}:`); g.push(`      return _words${cap(l)};`); }
g.push('    default:');
g.push(`      return _words${cap(LANGS[0])};`);
g.push('  }');
g.push('}');
for (const l of LANGS) {
  g.push('');
  g.push(`const List<Trivia> _trivia${cap(l)} = <Trivia>[`);
  for (const t of d.games.trivia[l]) g.push(`  Trivia(${q(t.q)}, ${q(t.a)}, <String>[${t.wrong.map(q).join(', ')}]),`);
  g.push('];');
  g.push('');
  g.push(`const List<Word> _words${cap(l)} = <Word>[`);
  for (const w of d.games.words[l]) g.push(`  Word(${q(w.w)}, ${q(w.hint)}),`);
  g.push('];');
}
files['i18n_games.dart'] = g.join('\n') + '\n';
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const f = path.join(out, name);
  const now = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  if (now === text) continue;
  stale++;
  if (flag === '--check') console.error(`out of date: ${name}`);
  else fs.writeFileSync(f, text);
}
console.log(`${keys.length} keys (${sdk.size} sdk.*) x ${LANGS.length} languages; ${flag === '--check' ? (stale ? `${stale} stale` : 'up to date') : `${stale} written`}`);
if (flag === '--check' && stale) process.exit(1);
JS
